export type User = {
	id: string;
	username: string;
	displayName: string;
	isAdmin: boolean;
	verified: boolean;
};
export type Mcp = {
	repository: string;
	documentation: string;
	deployment: 'hosted' | 'self-hosted' | 'both' | 'unknown';
	access: 'public' | 'internal' | 'restricted' | 'unknown';
	transport: 'http' | 'stdio' | 'sse' | 'unknown';
	endpoint: string;
	authentication: string;
	configuration: string;
	instructions: string;
	tools: string;
};
export type CatalogDetails = {
	applicationType: 'skill' | 'mcp';
	contexts: string[];
	techniques: string[];
	provenance: 'argonne' | 'external' | 'adapted';
	sourceUrl: string;
	upstreamAuthor: string;
	relevance: string;
	mcp: Mcp | null;
};
export type Category = { id: string; name: string; parent: string | null; count?: number };
export type ImportSource = {
	repository: string;
	directory: string;
	ref: string;
	commit: string;
	commitDate: string;
	author: string;
	licenses: { path: string; repositoryPath: string }[];
};
export type Skill = CatalogDetails & {
	id: string;
	name: string;
	description: string;
	ownerId: string;
	username: string;
	displayName: string;
	maintainerId: string;
	maintainerName: string;
	maintainerUsername: string;
	categories: string[];
	tags: string[];
	role: string;
	license: string;
	compatibility: string;
	updatedAt: string;
	revision: number;
	downloads: number;
	archived: boolean;
	source: ImportSource | null;
	example: string;
};
export type Revision = {
	details: CatalogDetails;
	id: string;
	number: number;
	createdAt: string;
	checksum: string;
	version: string;
	name: string;
	description: string;
	license: string;
	compatibility: string;
	files: { path: string; size: number; sha256: string }[];
	source: ImportSource | null;
};
